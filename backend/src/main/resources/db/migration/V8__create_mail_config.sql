CREATE TABLE mail_config (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    email_encrypted varchar(255),
    password_encrypted varchar(255),
    notification_recipient varchar(255),
    smtp_host varchar(255) NOT NULL DEFAULT 'localhost',
    smtp_port integer NOT NULL DEFAULT 1025,
    smtp_auth boolean NOT NULL DEFAULT false,
    smtp_ssl boolean NOT NULL DEFAULT false,
    updated_at timestamp(6) with time zone,
    CONSTRAINT pk_mail_config PRIMARY KEY (id)
);
