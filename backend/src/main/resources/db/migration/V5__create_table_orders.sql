CREATE TABLE orders (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    service_desk_number varchar(20) GENERATED ALWAYS AS ('SD-' || lpad(id::text, 8, '0')) STORED,
    title varchar(50) NOT NULL,
    description varchar(200),
    start_line date NOT NULL,
    dead_line date NOT NULL,
    completed_date timestamp(3) without time zone,
    agent_id bigint NOT NULL,
    client_id bigint NOT NULL,
    creation_date timestamp(3) without time zone NOT NULL,
    last_updated timestamp(3) without time zone NOT NULL,
    deleted boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT orders_pkey PRIMARY KEY (id),
    CONSTRAINT fk_orders_client_id FOREIGN KEY (client_id)
        REFERENCES clients (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT fk_orders_agent_id FOREIGN KEY (agent_id)
        REFERENCES agents (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);
